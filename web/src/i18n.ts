const dicts: Record<Locale, Record<MessageKey, string>> = { "zh-CN": zh, en };

const STORAGE_KEY = "bunrss:locale";

/** Saved preference first; otherwise Simplified Chinese (the app's original language). */
function detect(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "zh-CN" || saved === "en") return saved;
  } catch {
    // no localStorage (e.g. non-browser test)
  }
  return "zh-CN";
}

export const locale = ref<Locale>(detect());

export function setLocale(next: Locale) {
  locale.value = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // ignore
  }
  if (typeof document !== "undefined") document.documentElement.lang = next;
}

/** Translate a key for the active locale, replacing `{name}` placeholders. Reactive to `locale`. */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  let s: string = dicts[locale.value][key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
